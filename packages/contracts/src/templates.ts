export type Erc20Options = {
  kind: "erc20";
  name: string;
  symbol: string;
  premint: string;
  mintable: boolean;
  burnable: boolean;
  pausable: boolean;
  permit: boolean;
};

export type Erc721Options = {
  kind: "erc721";
  name: string;
  symbol: string;
  baseUri: string;
  mintable: boolean;
  burnable: boolean;
  pausable: boolean;
};

export type TemplateOptions = Erc20Options | Erc721Options;

export const SOLIDITY_PRAGMA = "^0.8.27";

export function contractIdentifier(name: string) {
  const words = name.normalize("NFKD").replace(/[^A-Za-z0-9 ]/g, " ").trim().split(/\s+/).filter(Boolean);
  const id = words.map((w) => w[0]!.toUpperCase() + w.slice(1)).join("");
  if (!id) return "MyContract";
  return /^[A-Za-z]/.test(id) ? id.slice(0, 64) : `C${id}`.slice(0, 64);
}

export function validateText(label: string, value: string, max: number) {
  if (!value.trim()) return `${label} can't be empty.`;
  if (value.length > max) return `${label} must be ${max} characters or fewer.`;
  if (/["\\\n\r]/.test(value)) return `${label} can't contain quotes, backslashes or line breaks.`;
  return null;
}

export function validateOptions(o: TemplateOptions): string | null {
  const nameError = validateText("Name", o.name, 50) ?? validateText("Symbol", o.symbol, 11);
  if (nameError) return nameError;
  if (!/^[A-Za-z0-9]+$/.test(o.symbol)) return "Symbol can only use letters and numbers.";
  if (o.kind === "erc20") {
    if (!/^\d{1,15}$/.test(o.premint)) return "Initial supply must be a whole number up to 15 digits.";
    if (o.premint === "0" && !o.mintable) return "With no initial supply, turn on minting or nobody can ever hold the token.";
  }
  if (o.kind === "erc721" && o.baseUri && (o.baseUri.length > 200 || /["\\\s]/.test(o.baseUri))) return "Base URI can't contain spaces, quotes or backslashes.";
  return null;
}

const lines = (...parts: (string | false | null | undefined)[]) => parts.filter((p): p is string => typeof p === "string").join("\n");

function erc20(o: Erc20Options) {
  const id = contractIdentifier(o.name);
  const bases = ["ERC20", o.burnable && "ERC20Burnable", o.pausable && "ERC20Pausable", "Ownable", o.permit && "ERC20Permit"].filter(Boolean) as string[];
  const needsUpdate = o.pausable;
  return {
    contractName: id,
    source: lines(
      "// SPDX-License-Identifier: MIT",
      "// Generated by Systema Contract Studio from OpenZeppelin Contracts 5.6",
      `pragma solidity ${SOLIDITY_PRAGMA};`,
      "",
      'import {ERC20} from "@openzeppelin/contracts/token/ERC20/ERC20.sol";',
      o.burnable && 'import {ERC20Burnable} from "@openzeppelin/contracts/token/ERC20/extensions/ERC20Burnable.sol";',
      o.pausable && 'import {ERC20Pausable} from "@openzeppelin/contracts/token/ERC20/extensions/ERC20Pausable.sol";',
      o.permit && 'import {ERC20Permit} from "@openzeppelin/contracts/token/ERC20/extensions/ERC20Permit.sol";',
      'import {Ownable} from "@openzeppelin/contracts/access/Ownable.sol";',
      "",
      `contract ${id} is ${bases.join(", ")} {`,
      "    constructor(address initialOwner)",
      `        ERC20("${o.name}", "${o.symbol}")`,
      "        Ownable(initialOwner)",
      o.permit && `        ERC20Permit("${o.name}")`,
      "    {",
      o.premint !== "0" && `        _mint(initialOwner, ${o.premint} * 10 ** decimals());`,
      "    }",
      o.pausable && "",
      o.pausable && "    function pause() public onlyOwner {\n        _pause();\n    }",
      o.pausable && "",
      o.pausable && "    function unpause() public onlyOwner {\n        _unpause();\n    }",
      o.mintable && "",
      o.mintable && "    function mint(address to, uint256 amount) public onlyOwner {\n        _mint(to, amount);\n    }",
      needsUpdate && "",
      needsUpdate &&
        "    function _update(address from, address to, uint256 value)\n        internal\n        override(ERC20, ERC20Pausable)\n    {\n        super._update(from, to, value);\n    }",
      "}",
      "",
    ),
  };
}

function erc721(o: Erc721Options) {
  const id = contractIdentifier(o.name);
  const bases = ["ERC721", o.burnable && "ERC721Burnable", o.pausable && "ERC721Pausable", "Ownable"].filter(Boolean) as string[];
  return {
    contractName: id,
    source: lines(
      "// SPDX-License-Identifier: MIT",
      "// Generated by Systema Contract Studio from OpenZeppelin Contracts 5.6",
      `pragma solidity ${SOLIDITY_PRAGMA};`,
      "",
      'import {ERC721} from "@openzeppelin/contracts/token/ERC721/ERC721.sol";',
      o.burnable && 'import {ERC721Burnable} from "@openzeppelin/contracts/token/ERC721/extensions/ERC721Burnable.sol";',
      o.pausable && 'import {ERC721Pausable} from "@openzeppelin/contracts/token/ERC721/extensions/ERC721Pausable.sol";',
      'import {Ownable} from "@openzeppelin/contracts/access/Ownable.sol";',
      "",
      `contract ${id} is ${bases.join(", ")} {`,
      o.mintable && "    uint256 private _nextTokenId;",
      o.mintable && "",
      "    constructor(address initialOwner)",
      `        ERC721("${o.name}", "${o.symbol}")`,
      "        Ownable(initialOwner)",
      "    {}",
      o.baseUri && "",
      o.baseUri && `    function _baseURI() internal pure override returns (string memory) {\n        return "${o.baseUri}";\n    }`,
      o.pausable && "",
      o.pausable && "    function pause() public onlyOwner {\n        _pause();\n    }",
      o.pausable && "",
      o.pausable && "    function unpause() public onlyOwner {\n        _unpause();\n    }",
      o.mintable && "",
      o.mintable && "    function safeMint(address to) public onlyOwner returns (uint256) {\n        uint256 tokenId = _nextTokenId++;\n        _safeMint(to, tokenId);\n        return tokenId;\n    }",
      o.pausable && "",
      o.pausable &&
        "    function _update(address to, uint256 tokenId, address auth)\n        internal\n        override(ERC721, ERC721Pausable)\n        returns (address)\n    {\n        return super._update(to, tokenId, auth);\n    }",
      "}",
      "",
    ),
  };
}

export function generate(o: TemplateOptions) {
  return o.kind === "erc20" ? erc20(o) : erc721(o);
}

export const DEFAULT_ERC20: Erc20Options = { kind: "erc20", name: "Acme Points", symbol: "ACME", premint: "1000000", mintable: true, burnable: true, pausable: false, permit: true };
export const DEFAULT_ERC721: Erc721Options = { kind: "erc721", name: "Acme Passes", symbol: "PASS", baseUri: "", mintable: true, burnable: false, pausable: false };
